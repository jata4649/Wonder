import { ROLE_DECAY } from './balance';
import type { CasterDef, DrawShotDef, Role, SkillDef, SkillKind } from './types';

const sk = (
  id: string,
  name: string,
  glyph: string,
  kind: SkillKind,
  mpCost: number,
  cooldown: number,
  requiredLevel: number,
  effect: string,
  params: Record<string, number>,
  desc: string,
): SkillDef => ({ id, name, glyph, kind, mpCost, cooldown, requiredLevel, effect, params, desc });

const ws = (id: string, name: string, glyph: string, kind: SkillKind, effect: string, params: Record<string, number>, desc: string) =>
  sk(id, name, glyph, kind, 0, 0, 5, effect, params, desc);

function draw(role: Role, d: Partial<DrawShotDef> & Pick<DrawShotDef, 'type' | 'range'>): DrawShotDef {
  const decaying = d.type === 'curve';
  return {
    mpCost: 10,
    drawLength: d.range * 1.2,
    baseSpeed: 0,
    speedUpStraight: 1,
    speedDownSharp: 1,
    width: 30,
    power: 70,
    decay: decaying ? ROLE_DECAY[role] : [1],
    piercePower: 0,
    pierceDecay: decaying,
    maxHits: 0,
    down: true,
    multiShot: 1,
    soloCross: false,
    coreMult: 1,
    ...d,
  };
}

